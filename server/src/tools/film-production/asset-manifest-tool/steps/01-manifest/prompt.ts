/**
 * tools/film-production/asset-manifest-tool/steps/01-manifest/prompt.ts
 * 全剧资产清单发现提示词 (Asset Manifest Prompt SSOT)
 */

export function buildAssetManifestPrompt(params: {
  title?: string;
  storyMarkdown: string;
  prd?: any;
}): string {
  const { title, storyMarkdown, prd } = params;

  return `你是一名享誉好莱坞的资深电影制片统筹与选角总监（Film Production Coordinator & Script Breakdown Supervisor）。
请依据影视工业标准剧本分解规范（Hollywood Script Breakdown Pipeline），通读剧本与策划案，提炼全剧的高信噪比核心资产清单：

【故事标题】：${title || '未命名影视项目'}

【策划案/世界观大纲】：
\`\`\`json
${JSON.stringify(prd || {}, null, 2)}
\`\`\`

【剧本正文】：
\`\`\`markdown
${storyMarkdown || '请结合项目剧情提取出场资产'}
\`\`\`

【影视工业三大资产分类与收敛刚性公理（SSOT · 100% 通用无偏）】：
1. 🎭【角色公理 (Speaking Cast & Agency)】：
   - 必须以剧本中真正有对白发言、独立台词交互或主导核心戏剧冲突的能动主体为准；
   - 具象化灵异实体、人形傀儡、非人化身或关键智能造物，只要具备独立戏剧交互能动性，100% 统一定性为角色（严禁被误定为道具或场景陈设）；
   - 100% 绝对严禁提取泛用无名路人、背景群演或单次功能性过客；
   - 准入原则：按剧情实际需要收敛，仅保留推动主线与分支因果的核心主角与重要配角。

2. 🏛️【独立可拍摄物理空间公理 (Independent Space Breakdown)】：
   - 必须以**视觉独立的物理空间/房间（Room / Independent Shootable Space）**为最小定妆单元（例如“主厅堂”与“室外庭院”是室内外两个截然不同的空间，或“客厅”与“书房”是两间独立房间），**严禁把整栋建筑或整个院落笼统合并为一个大场景**，否则一张定妆图无法同时代表室内和室外；
   - **拆分判据**：只要两个区域之间存在物理隔断（墙体/大门）或室内外切换，导致背景建筑、地面材质或主光源完全不同，且两处都有实质戏份，就必须拆分为各自独立的场景各自定妆；
   - **防碎片化边界（\`subScenes\` 收拢）**：同一物理空间内部的局部位置、家具角落或机位视点（如同一房间内的“桌案前”、“侧门边”、“窗边”），绝对严禁拆成独立场景，必须收拢进该空间的 \`subScenes\` 数组；
   - **命名清晰**：场景名称需具体到空间本身（如“XX宅正厅”、“XX宅院落”或“主卧”、“走廊”），不要只写笼统的大建筑名。

3. 🗝️【道具准入铁律公理 (Hero Props & In-Hand Agency)】：
   - 严禁机械设置死板数量上限，严格以“剧本显式信物标记”与“因果推动能动性”为准入判据：
     a. ⚠️【剧本显式信物 100% 必须准入】：凡剧本正文或大纲中明确标有【获得关键道具：...】、【获得道具】、【关键信物】等剧本专属标注的物件，属于叙事核心支柱，100% 必须完整提取，严禁遗漏；
     b. 【主角核心职业装置/随身标志物】：角色核心专属装置且在全剧多场次被手持操作、承载视听或感知机制的随身信物（如录音师的便携录音机、法医的勘验箱），必须提取为关键道具；
     c. 【关键因果与解谜信物 (Hero Props)】：被演员亲手握持、抓取、翻阅、交付，且承载核心解谜、规则证物或终局逆转的关键信物（如特定日记册、刻名信物、解谜钥匙等）；
   - ⚠️【绝对刚性禁令 · 严禁提取生活环境陈设】：凡是摆在背景、挂在墙上、放在桌案上但未承载核心解谜/因果机制的生活陈设与家具（如普通香炉、烛台、挂画、茶杯、桌椅、门槛），100% 属于场景固定硬装，绝对严禁作为独立道具提取！

4. 📌【PRD 锚点优先对齐】：
   - 优先继承工序 1（Planner）在策划案 PRD 中已经确立的角色、核心空间与关键信物名称，保持全剧术语 100% 一致，严禁随意更名。

请输出严格符合 AssetManifestOutputSchema 的 JSON。`;
}
