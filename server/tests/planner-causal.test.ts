import assert from 'node:assert/strict';
import {initialWorld,applyAction,sharedWorld,groupEndings,causalNode,partitionEndings,type Fact} from '../src/tools/planner/screenplay-tool/steps/01-premise/causal.js';
const facts:Fact[]=[{key:'evidence',scope:'branch',meaning:'证据归属',values:['档案柜','主角'],initial:'档案柜'},{key:'place',scope:'shared',meaning:'主角位置',values:['档案室','出口'],initial:'档案室'}];
const start=[{history:{},world:initialWorld(facts)}];
const take={summary:'拿走证据',requires:{evidence:'档案柜'},effects:{evidence:'主角'}};
const a=applyAction(facts,start,take).map(r=>({...r,history:{decision_1:true}}));
const b=start.map(r=>({...r,history:{decision_1:false}}));
const merged=[...a,...b];
assert.deepEqual(sharedWorld(merged),{place:'档案室'});
assert.throws(()=>applyAction(facts,merged,{summary:'出示证据',requires:{evidence:'主角'},effects:{}}),/前提不成立/);
assert.throws(()=>applyAction(facts,merged,take),/前提不成立/);
assert.throws(()=>applyAction(facts,merged,{summary:'凭空补证据',requires:{},effects:{evidence:'主角'}}),/不能重置/);
assert.throws(()=>applyAction(facts,start,{summary:'非法物品',requires:{},effects:{unknown:'x'}}),/未注册/);
assert.throws(()=>applyAction(facts,start,{summary:'非法值',requires:{},effects:{evidence:'天上'}}),/未注册/);
const leave={summary:'走到出口',requires:{place:'档案室'},effects:{place:'出口'}};
const after=applyAction(facts,merged,leave);
assert.equal(after[0].world.evidence,'主角');assert.equal(after[1].world.evidence,'档案柜');
const groups=groupEndings(facts,after,[{requires:{evidence:'主角'}},{requires:{evidence:'档案柜'}}]);
assert.deepEqual(groups.map(g=>g.map(r=>r.history.decision_1)),[[true],[false]]);
assert.throws(()=>groupEndings(facts,after,[{requires:{evidence:'主角'}}]),/唯一覆盖/);
assert.throws(()=>groupEndings(facts,after,[{requires:{}},{requires:{evidence:'主角'}}]),/唯一覆盖/);
const node=causalNode(facts,'common',2,'common',merged,leave);
assert.deepEqual(node.causalContract?.unavailableFacts,['证据归属']);
assert(!node.entryConditions.some(s=>s.includes('证据')));
console.log('causal fact propagation regression passed');

